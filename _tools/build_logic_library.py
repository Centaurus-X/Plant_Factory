#!/usr/bin/env python3
"""Build the deterministic browser representation of PF-LOGIC-V1."""

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'config' / 'logic_block_library_v1.json'
TARGET = ROOT / 'public' / 'js' / 'logic_library.js'


def parse_args(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    return parser.parse_args(argv)


def read_source():
    payload = json.loads(SOURCE.read_text(encoding='utf-8'))
    blocks = payload.get('blocks')
    if not isinstance(blocks, list) or not blocks:
        raise ValueError('logic block library has no blocks')
    seen = set()
    for block in blocks:
        block_type = str(block.get('block_type') or '').strip()
        if not block_type:
            raise ValueError('block_type missing')
        if block_type in seen:
            raise ValueError('duplicate block_type: %s' % block_type)
        seen.add(block_type)
        ports = block.get('ports')
        if not isinstance(ports, list):
            raise ValueError('ports must be a list: %s' % block_type)
        port_ids = set()
        for port in ports:
            port_id = str(port.get('id') or '').strip()
            if not port_id:
                raise ValueError('port id missing: %s' % block_type)
            if port_id in port_ids:
                raise ValueError('duplicate port %s.%s' % (block_type, port_id))
            port_ids.add(port_id)
            if port.get('direction') not in ('in', 'out'):
                raise ValueError('invalid direction: %s.%s' % (block_type, port_id))
    return payload


def render_module(payload):
    body = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    return """/**
 * logic_library.js — generated PF-LOGIC-V1 block and target contract.
 *
 * Source: config/logic_block_library_v1.json
 * Generator: _tools/build_logic_library.py
 * Do not edit this file manually.
 */

'use strict';

const LIBRARY_DATA = %s;

export const LOGIC_LIBRARY = Object.freeze(LIBRARY_DATA);
export const LOGIC_STANDARD = Object.freeze(LIBRARY_DATA.standard);
export const LOGIC_BLOCKS = Object.freeze(LIBRARY_DATA.blocks);
export const LOGIC_TARGETS = Object.freeze(LIBRARY_DATA.targets);
export const LOGIC_DATA_TYPES = Object.freeze(LIBRARY_DATA.data_types);
export const LOGIC_CATEGORIES = Object.freeze(LIBRARY_DATA.categories);
""" % body


def main(argv=None):
    args = parse_args(argv or sys.argv[1:])
    payload = read_source()
    rendered = render_module(payload)
    if args.check:
        if not TARGET.exists():
            print('missing generated logic library: %s' % TARGET, file=sys.stderr)
            return 1
        current = TARGET.read_text(encoding='utf-8')
        if current != rendered:
            print('logic library is not deterministic/current', file=sys.stderr)
            return 1
        print('PF-LOGIC-V1 library verified: %d blocks.' % len(payload['blocks']))
        return 0
    TARGET.write_text(rendered, encoding='utf-8')
    print('Generated %s with %d blocks.' % (TARGET.relative_to(ROOT), len(payload['blocks'])))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
